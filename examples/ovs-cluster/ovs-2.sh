#!/usr/bin/env bash
# OVN shared bridge — ovs-2 (192.168.128.42): chassis only.
# Joins the cluster center on ovs-0 and attaches this host to the logical
# switch "shared" (the switch and its ports are defined by ovs-0.sh).
#
# It is also the backup gateway chassis of r0's uplink leg (ovs-1 is the
# primary): VLAN 1280 in netns real-uplink, bridged into OVN as localnet
# "uplink". OVN fails over between ovs-1 and ovs-2 via BFD on the tunnels.
#
#   ./ovs-2.sh up     install, join ovs-0, attach shared0, wire the uplink
#   ./ovs-2.sh down   remove the uplink, detach shared0, leave OVN
#
# Run ovs-0.sh first.
#
# Underlay:      ovs-0 .40   ovs-1 .41   ovs-2 .42   ovs-3 .43  (192.168.128.0/24)
# Shared bridge: 10.99.0.0/24, each host gets 10.99.0.<last underlay octet>
# Firewall:      TCP 6642 to ovs-0, UDP 6081 (Geneve) between all hosts
set -euo pipefail

NAME=ovs-2
LOCAL_IP=192.168.128.42
CENTRAL_IP=192.168.128.40
PORT=shared0
MTU=1442                     # 1500 - 58 bytes Geneve overhead
MY_ADDR=10.99.0.42/24
# shared0 lives in its own netns "shared0" with a default route via r0
PORT_NS=shared0
PORT_GW=10.99.0.1
PORT_HELPER=/usr/local/sbin/shared0-netns-up
PORT_UNIT=shared0-netns.service
OLD_NETWORK_FILE=/etc/systemd/network/50-shared0.network   # earlier variant
MY_MAC=0a:00:0a:63:00:42

# real uplink for r0 (ovs-0.sh defines r0-uplink 192.168.132.120 on it):
# vlan.1280 on "host" lives in netns real-uplink and is bridged there, layer 2
# only, through a veth pair to the OVS bridge br-uplink (localnet "uplink").
# The root namespace has no address on 192.168.132.0/24.
#
#   host ── vlan.1280 ─┐                  netns real-uplink
#                      br-real ── ul-ns ══ ul-ovs ── br-uplink ── OVN localnet
UPLINK_PARENT=host
UPLINK_VLAN=1280
UPLINK_DEV=vlan.$UPLINK_VLAN
UPLINK_NS=real-uplink
UPLINK_NS_BR=br-real
UPLINK_VETH_NS=ul-ns
UPLINK_VETH_OVS=ul-ovs
UPLINK_BR=br-uplink
UPLINK_NET=uplink              # = network_name of the localnet port in ovs-0.sh
UPLINK_HELPER=/usr/local/sbin/real-uplink-up
UPLINK_UNIT=real-uplink.service

install_deps() {
  # Ubuntu 26.04: OVS + OVN packages and the tools the script uses
  export DEBIAN_FRONTEND=noninteractive
  apt-get update
  apt-get install -y iproute2 kmod procps openvswitch-switch openvswitch-common ovn-common ovn-host
  OVS_SVC=openvswitch-switch
  CONTROLLER_SVC=ovn-host
  systemctl enable --now "$OVS_SVC"
  ovs-vsctl --timeout=30 show >/dev/null   # wait until ovsdb-server answers
}

down() {
  ovs-vsctl --if-exists remove open_vswitch . external_ids ovn-bridge-mappings
  ovs-vsctl --if-exists del-br "$UPLINK_BR"
  systemctl disable --now "$UPLINK_UNIT" 2>/dev/null || true
  rm -f "/etc/systemd/system/$UPLINK_UNIT" "$UPLINK_HELPER"
  systemctl daemon-reload
  ip link del "$UPLINK_VETH_OVS" 2>/dev/null || true
  ip netns del "$UPLINK_NS" 2>/dev/null || true   # takes vlan.1280 with it

  ovs-vsctl --if-exists del-port br-int "$PORT"
  systemctl disable --now "$PORT_UNIT" 2>/dev/null || true
  rm -f "/etc/systemd/system/$PORT_UNIT" "$PORT_HELPER"
  systemctl daemon-reload
  ip netns del "$PORT_NS" 2>/dev/null || true
  systemctl stop ovn-host || true
  echo "$NAME: shared bridge removed"
}

up() {
  install_deps
  modprobe openvswitch 2>/dev/null || true
  modprobe geneve 2>/dev/null || true

  # --- chassis: join the SB on ovs-0
  # ovs-ctl (--system-id=random) copies this file into external_ids:system-id
  # at every start; without it the chassis comes back as a random (or cloned)
  # UUID after a reboot and collides with its old encap ip.
  echo "$NAME" > /etc/openvswitch/system-id.conf
  ovs-vsctl set open_vswitch . \
    external_ids:system-id="$NAME" \
    external_ids:ovn-remote="tcp:$CENTRAL_IP:6642" \
    external_ids:ovn-encap-type=geneve \
    external_ids:ovn-encap-ip="$LOCAL_IP"
  systemctl enable --now "$CONTROLLER_SVC"

  # ovn-controller creates br-int; wait for it
  for _ in $(seq 1 30); do ovs-vsctl br-exists br-int && break; sleep 1; done
  ovs-vsctl br-exists br-int || { echo "$NAME: br-int did not appear" >&2; exit 1; }

  # --- attach this host (iface-id must match the lsp name ovs-0 created)
  ovs-vsctl --may-exist add-port br-int "$PORT" -- set interface "$PORT" \
    type=internal mac="\"$MY_MAC\"" external_ids:iface-id="$NAME" \
    mtu_request="$MTU"

  # shared0 goes into netns shared0. ovs-vswitchd (re)creates the internal
  # device in the root namespace (also at every boot), so a oneshot unit moves
  # it over and sets mtu, address and the default route via r0 inside the netns.
  if [ -e "$OLD_NETWORK_FILE" ]; then rm -f "$OLD_NETWORK_FILE"; networkctl reload; fi
  cat >"$PORT_HELPER" <<EOF
#!/bin/sh
# generated by $NAME.sh: puts $PORT into netns $PORT_NS (idempotent)
set -e
[ -e /run/netns/$PORT_NS ] || ip netns add $PORT_NS
ip -n $PORT_NS link set lo up
i=0
until ip -n $PORT_NS link show $PORT >/dev/null 2>&1; do
  if ip link show $PORT >/dev/null 2>&1; then
    ip link set $PORT netns $PORT_NS
  else
    i=\$((i + 1))
    [ \$i -lt 60 ] || { echo "$PORT did not appear" >&2; exit 1; }
    sleep 1
  fi
done
ip -n $PORT_NS link set $PORT mtu $MTU up
ip -n $PORT_NS addr replace $MY_ADDR dev $PORT
ip -n $PORT_NS route replace default via $PORT_GW dev $PORT
EOF
  chmod 755 "$PORT_HELPER"
  cat >"/etc/systemd/system/$PORT_UNIT" <<EOF
[Unit]
Description=$PORT in netns $PORT_NS, default via $PORT_GW
Wants=ovs-vswitchd.service
After=ovs-vswitchd.service openvswitch-switch.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$PORT_HELPER

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable "$PORT_UNIT"
  systemctl restart "$PORT_UNIT"

  # --- real uplink. netns, vlan, bridge and veth are kernel runtime state, so
  # a oneshot unit rebuilds them at every boot, before ovs-vswitchd starts.
  cat >"$UPLINK_HELPER" <<EOF
#!/bin/sh
# generated by $NAME.sh — rebuilds the real-uplink netns (idempotent)
set -e
[ -e /run/netns/$UPLINK_NS ] || ip netns add $UPLINK_NS
ip -n $UPLINK_NS link set lo up
if ! ip -n $UPLINK_NS link show $UPLINK_DEV >/dev/null 2>&1; then
  ip link add link $UPLINK_PARENT name $UPLINK_DEV type vlan id $UPLINK_VLAN
  ip link set $UPLINK_DEV netns $UPLINK_NS
fi
ip -n $UPLINK_NS link show $UPLINK_NS_BR >/dev/null 2>&1 ||
  ip -n $UPLINK_NS link add $UPLINK_NS_BR type bridge
ip link show $UPLINK_VETH_OVS >/dev/null 2>&1 ||
  ip link add $UPLINK_VETH_OVS type veth peer name $UPLINK_VETH_NS netns $UPLINK_NS
ip -n $UPLINK_NS link set $UPLINK_DEV master $UPLINK_NS_BR up
ip -n $UPLINK_NS link set $UPLINK_VETH_NS master $UPLINK_NS_BR up
ip -n $UPLINK_NS link set $UPLINK_NS_BR up
ip link set $UPLINK_VETH_OVS up
EOF
  chmod 755 "$UPLINK_HELPER"
  cat >"/etc/systemd/system/$UPLINK_UNIT" <<EOF
[Unit]
Description=real-uplink netns: $UPLINK_DEV bridged to $UPLINK_VETH_OVS
Before=ovs-vswitchd.service openvswitch-switch.service ovn-controller.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$UPLINK_HELPER

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable --now "$UPLINK_UNIT"

  # OVS side: br-uplink carries the localnet "uplink" (both kept in conf.db)
  ovs-vsctl --may-exist add-br "$UPLINK_BR"
  ovs-vsctl --may-exist add-port "$UPLINK_BR" "$UPLINK_VETH_OVS"
  ovs-vsctl set open_vswitch . external_ids:ovn-bridge-mappings="$UPLINK_NET:$UPLINK_BR"

  echo "$NAME: $PORT = $MY_ADDR in netns $PORT_NS, default via $PORT_GW"
  echo "uplink: $UPLINK_DEV in netns $UPLINK_NS -> $UPLINK_BR (backup gateway chassis for r0-uplink)"
  echo "check: ip netns exec $PORT_NS ping -c2 $PORT_GW"
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  *) echo "usage: $0 up|down" >&2; exit 2 ;;
esac

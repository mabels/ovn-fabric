"""Templates → a generated Python module: one function per sample that
returns what the primitive does to RawIR, from its parameters.

A placeholder becomes the parameter (`{netns}` → `netns`), a transform a
call of the module's own helper (`{addr|ip}` → `_ip(addr)`), a string
with placeholders inside an f-string. The module is self-contained, typed
and meant to be regenerated, never edited.
"""

from __future__ import annotations

import re
from typing import Any

_PLACEHOLDER = re.compile(r"\{([a-z_0-9]+)(?:\|([a-z]+))?\}")

# The helpers the transforms (learn.TRANSFORMS) become in the module.
_HELPERS = """
def _ip(value: str) -> str:
    return str(ipaddress.ip_interface(value).ip)


def _len(value: str) -> int:
    return ipaddress.ip_interface(value).network.prefixlen


def _net(value: str) -> str:
    return str(ipaddress.ip_interface(value).network)


def _canonical(value: str) -> str:
    return str(ipaddress.ip_interface(value))


def _broadcast(value: str) -> str:
    return str(ipaddress.ip_interface(value).network.broadcast_address)


def _netaddr(value: str) -> str:
    return str(ipaddress.ip_interface(value).network.network_address)


def _family(value: Any) -> int | None:
    try:
        return ipaddress.ip_interface(value).version
    except ValueError:
        return None
"""

# The address family a marker kind was learned with.
_FAMILY = {"cidr": 4, "net": 4, "ip": 4, "cidr6": 6, "net6": 6, "ip6": 6}

_CALL = {
    "": "{}",
    "lower": "{}.lower()",
    "upper": "{}.upper()",
    "ip": "_ip({})",
    "len": "_len({})",
    "net": "_net({})",
    "canonical": "_canonical({})",
    "broadcast": "_broadcast({})",
    "netaddr": "_netaddr({})",
}


def _expr(param: str, transform: str | None) -> str:
    return _CALL[transform or ""].format(param)


def expression(value: Any) -> str:
    """The Python source of a template value."""
    if isinstance(value, dict):
        items = ", ".join(f"{expression(key)}: {expression(item)}" for key, item in value.items())
        return "{" + items + "}"
    if isinstance(value, list):
        return "[" + ", ".join(expression(item) for item in value) + "]"
    if not isinstance(value, str) or not _PLACEHOLDER.search(value):
        return repr(value)
    whole = _PLACEHOLDER.fullmatch(value)
    if whole:
        return _expr(whole.group(1), whole.group(2))
    parts: list[str] = []
    last = 0
    for match in _PLACEHOLDER.finditer(value):
        parts.append(value[last : match.start()].replace("{", "{{").replace("}", "}}"))
        parts.append("{" + _expr(match.group(1), match.group(2)) + "}")
        last = match.end()
    parts.append(value[last:].replace("{", "{{").replace("}", "}}"))
    literal = "".join(parts)
    quote = '"' if '"' not in literal else "'"
    return f"f{quote}{literal}{quote}"


def _parts(element: str) -> list[str]:
    return re.findall(r"\{([a-z_0-9]+)\}", element)


def _each_body(cls: str, each: dict[str, str]) -> list[str]:
    """The loop that applies one learned element to every element of the
    `each` field (one per sample)."""
    ((field, element),) = each.items()
    parts = _parts(element)
    pattern = "".join(
        f"(?P<{piece[1:-1]}>.+?)" if piece.startswith("{") else re.escape(piece)
        for piece in re.split(r"(\{[a-z_0-9]+\})", element)
        if piece
    )
    return [
        "    added: dict[str, Any] = {}",
        "    changed: dict[str, Any] = {}",
        f"    for element in {field}:",
        f"        match = re.fullmatch({pattern!r}, element)",
        "        if match is None:",
        "            raise NotLearned(",
        f'                f"{cls}.{field}: {{element!r}} is no '
        f'{element.replace("{", "{{").replace("}", "}}")!r}"',
        "            )",
        f"        {', '.join(parts)}, = {', '.join(f'match.group({p!r})' for p in parts)},",
    ]


def render(templates: dict[str, Any], source: str) -> str:
    """The library for `templates` (primate's learn result)."""
    out = [
        f'"""Generated by primate ({source}) — do not edit; regenerate.',
        "",
        "What each primitive (fabric/primitives) does to RawIR, learned on a real",
        "system (ADR 0008): `rawir(primitive)` for a primitive object, or the function",
        "of its class with its fields. A footprint is the nodes the primitive",
        'adds and the fields it changes on nodes that were there."""',
        "",
        "from __future__ import annotations",
        "",
        "import dataclasses",
        "import ipaddress",
        "import re",
        "from collections.abc import Callable",
        "from typing import Any",
        "",
        "Footprint = dict[str, Any]  # {'added': {id: node}, 'changed': {id: {field: change}}}",
        "",
        "",
        "class NotLearned(ValueError):",
        '    """No learned footprint for this primitive or these values."""',
        "",
        _HELPERS,
    ]
    table: dict[str, list[str]] = {}
    volatile: dict[str, list[str]] = {}
    for name in sorted(templates):
        template = templates[name]
        if "error" in template:
            out += ["", f"# {template['class']}: not learned — {template['error']}", ""]
            continue
        params = ", ".join(f"{param}: {kind}" for param, kind in template["params"].items())
        out += ["", f"def {name}(*, {params}) -> Footprint:"]
        out.append(
            f'    """{template["class"]} (learned with {template["fixed"] or "markers only"})."""'
        )
        for field, value in template["fixed"].items():
            differs = "is not" if value is None or isinstance(value, bool) else "!="
            out += [
                f"    if {field} {differs} {value!r}:",
                f"        raise NotLearned(f\"{template['class']}.{field}={{{field}!r}}: "
                f'learned only with {value!r}")',
            ]
        shapes = template.get("shapes", {})
        pairs = template.get("pairs", {})
        each = template.get("each", {})
        # A marked field that may be None was learned with a value only
        # (the root netns' name None is no netns `netns:None`).
        for field, kind in template["params"].items():
            if field in template["fixed"] or field in shapes or field in pairs or field in each:
                continue
            if "None" in kind:
                out += [
                    f"    if {field} is None:",
                    f'        raise NotLearned("{template["class"]}.{field}=None: '
                    'learned only with a value")',
                ]
        for field, count in shapes.items():
            names = ", ".join(f"{field}_{i}" for i in range(count))
            out += [
                f"    if len({field}) != {count}:",
                f'        raise NotLearned(f"{template["class"]}.{field}: {{len({field})}} '
                f'elements, learned only with {count}")',
                f"    ({names},) = {field}",
            ]
        for field, keys in pairs.items():
            names = ", ".join(f"{field}_{i}" for i in range(len(keys)))
            out += [
                f"    if tuple(key for key, _ in {field}) != {tuple(keys)!r}:",
                f'        raise NotLearned(f"{template["class"]}.{field}: keys '
                f'{{[key for key, _ in {field}]}}, learned only with {list(keys)}")',
                f"    ({names},) = (value for _, value in {field})",
            ]
        # An address learned as IPv4 says nothing about an IPv6 one.
        for marker, kind in template.get("kinds", {}).items():
            if kind in _FAMILY and not any(marker in _parts(f) for f in each.values()):
                out += [
                    f"    if _family({marker}) != {_FAMILY[kind]}:",
                    f'        raise NotLearned(f"{template["class"]}.{marker}={{{marker}!r}}: '
                    f'learned only with IPv{_FAMILY[kind]}")',
                ]
        used = repr(template["added"]) + repr(template["changed"])
        unused = [
            p
            for p in template["params"]
            if p not in template["fixed"]
            and p not in shapes
            and p not in pairs
            and p not in each
            and "{" + p + "}" not in used
            and "{" + p + "|" not in used
        ]
        if unused:
            out.append(f"    del {', '.join(unused)}  # not in RawIR")
        if each:
            out += _each_body(template["class"], each)
        out += [
            "    return {",
            f"        'added': {expression(template['added'])},",
            f"        'changed': {expression(template['changed'])},",
            "    }",
            "",
        ]
        if each:
            out[-5:] = [
                f"        added.update({expression(template['added'])})",
                f"        changed.update({expression(template['changed'])})",
                "    return {'added': added, 'changed': changed}",
                "",
            ]
        table.setdefault(template["class"], []).append(name)
        merged = volatile.setdefault(template["class"], [])
        merged += [field for field in template["volatile"] if field not in merged]
    out += [
        "",
        "# The primitive's class name -> its learned functions, one per shape",
        "# (sample variant), tried in order.",
        "_BY_CLASS: dict[str, tuple[Callable[..., Footprint], ...]] = {",
        *(f"    {cls!r}: ({', '.join(names)},)," for cls, names in table.items()),
        "}",
        "",
        "# Fields the system fills in differently every time (not compared).",
        f"VOLATILE: dict[str, list[str]] = {volatile!r}",
        "",
        "",
        "def rawir(primitive: Any) -> Footprint:",
        '    """What `primitive` does to RawIR."""',
        "    shapes = _BY_CLASS.get(type(primitive).__name__)",
        "    if shapes is None:",
        '        raise NotLearned(f"{type(primitive).__name__}: not learned")',
        "    fields = {f.name: getattr(primitive, f.name) for f in dataclasses.fields(primitive)}",
        "    reasons: list[str] = []",
        "    for learned in shapes:",
        "        try:",
        "            return learned(**fields)",
        "        except NotLearned as exc:",
        "            reasons.append(str(exc))",
        '    raise NotLearned("; ".join(reasons))',
        "",
    ]
    return "\n".join(out)
